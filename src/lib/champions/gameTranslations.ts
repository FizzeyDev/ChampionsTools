// Reverse lookup (French name -> English canonical name), built once.
const REVERSE: Record<Kind, Record<string, string>> = {
  species: {},
  move: {},
  ability: {},
  item: {},
  nature: {},
};
for (const kind of Object.keys(TABLES) as Kind[]) {
  for (const [en, fr] of Object.entries(TABLES[kind])) {
    REVERSE[kind][fr.toLowerCase()] = en;
  }
}

/** English canonical name -> French name for display. Falls back to the
 * English name itself if untranslated (should be rare — coverage is
 * essentially complete for everything actually selectable in the app). */
/** English canonical name -> French name for display. Falls back to the
 * English name itself if untranslated (should be rare — coverage is
 * essentially complete for everything actually selectable in the app). */
export function toFrench(kind: Kind, enName: string): string {
  return TABLES[kind][enName] ?? enName;
}

export function toFrenchNature(enName: string): string {
  return NATURES_FR[enName] ?? enName;
}

export function toFrenchType(enName: string): string {
  return TYPES_FR[enName] ?? enName;
}

function foldAccents(s: string): string {
  return s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

/** True if `query` matches `enName` in either language — used so search
 * works regardless of the site's current UI language (e.g. typing
 * "Sarmurai" finds Golisopod even with the English interface active, and
 * "Golisopod" still works with the French interface active). Accents are
 * ignored on both sides so "Sarmurai" also matches "Sarmuraï". */
export function matchesBilingual(kind: Kind, enName: string, query: string): boolean {
  const q = foldAccents(query.trim());
  if (!q) return true;
  if (foldAccents(enName).includes(q)) return true;
  const fr = TABLES[kind][enName];
  return !!fr && foldAccents(fr).includes(q);
}